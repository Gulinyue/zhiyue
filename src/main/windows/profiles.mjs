

const DASHBOARD_WINDOW_WIDTH = 1120;
const DASHBOARD_WINDOW_HEIGHT = 720;
const DASHBOARD_WINDOW_MIN_WIDTH = 900;
const DASHBOARD_WINDOW_MIN_HEIGHT = 600;
const FOCUS_WINDOW_WIDTH = 1e3;
const FOCUS_WINDOW_HEIGHT = 480;
const FOCUS_WINDOW_MIN_WIDTH = 420;
const FOCUS_WINDOW_MIN_HEIGHT = 400;
const WINDOW_CHROME_OPTIONS = {
  resizable: true
};
function getWindowSurfaceProfile(surface) {
  return surface === "focus" ? {
    width: FOCUS_WINDOW_WIDTH,
    height: FOCUS_WINDOW_HEIGHT,
    minWidth: FOCUS_WINDOW_MIN_WIDTH,
    minHeight: FOCUS_WINDOW_MIN_HEIGHT
  } : {
    width: DASHBOARD_WINDOW_WIDTH,
    height: DASHBOARD_WINDOW_HEIGHT,
    minWidth: DASHBOARD_WINDOW_MIN_WIDTH,
    minHeight: DASHBOARD_WINDOW_MIN_HEIGHT
  };
}

export { DASHBOARD_WINDOW_WIDTH, DASHBOARD_WINDOW_HEIGHT, DASHBOARD_WINDOW_MIN_WIDTH, DASHBOARD_WINDOW_MIN_HEIGHT, FOCUS_WINDOW_WIDTH, FOCUS_WINDOW_HEIGHT, FOCUS_WINDOW_MIN_WIDTH, FOCUS_WINDOW_MIN_HEIGHT, WINDOW_CHROME_OPTIONS, getWindowSurfaceProfile };
